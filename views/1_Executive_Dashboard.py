"""Module 1 — Executive Dashboard."""
import plotly.graph_objects as go
import streamlit as st

from components import charts, layout
from components.kpi_cards import kpi_row
from components.theme import AMBER, BLUE, GREEN, PINK, PURPLE, RED, TURQUOISE
from analytics import kpis, occupancy
from utils import state
from utils.formatting import money, num, pct

T = state.get_data()
F = state.get_filtered()
mo = state.get_monthly()

if mo.empty:
    st.warning("No data in the selected period.")
    st.stop()

cur = mo.iloc[-1]
K = kpis.executive_kpis(*state.get_kpi_context())
layout.page_header("Module 1 · Executive overview", "Executive Dashboard",
                   "A real-time view of membership health, revenue and operations for decision makers.",
                   chips=[f"Reporting month: {cur['month']:%B %Y}", f"{len(mo)} months in view"])


def card(key, label, fmt, icon, accent, better=True, mode="relative", spark=True):
    k = K[key]
    return dict(label=label, value=fmt(k["value"]), cur=k["value"], prev=k["prev"], icon_name=icon,
                accent=accent, higher_is_better=better, delta_mode=mode, spark=k["spark"] if spark else None)


kpi_row([
    card("total_members", "Total members", num, "users", PURPLE),
    card("active_members", "Active members", num, "activity", TURQUOISE),
    card("inactive_members", "Inactive members", num, "user-x", PINK, better=False),
    card("revenue", "Monthly revenue", money, "dollar", GREEN),
])
st.write("")
kpi_row([
    card("renewal_rate", "Renewal rate", pct, "refresh", BLUE, mode="points"),
    card("avg_daily_visits", "Avg daily attendance", lambda v: num(v, 0), "clock", AMBER),
    card("member_growth", "Monthly member growth", lambda v: pct(v, 2, signed=True), "trend-up", TURQUOISE,
         mode="points"),
    card("profit", "Estimated profit", money, "pie", PURPLE),
])
st.write("")
kpi_row([
    card("expenses", "Total expenses", money, "card", RED, better=False),
    card("churn_rate", "Monthly churn rate", pct, "trend-down", PINK, better=False, mode="points"),
    card("arpu", "Revenue per member", lambda v: money(v, 2), "target", GREEN),
    card("new_members", "New registrations", num, "user-plus", BLUE),
])

layout.section("Financial performance", "Revenue, expenses and estimated profit per month")
if state.get_filters()[2]:
    st.caption("Membership-type filter active: gym-wide expenses are allocated pro rata to the selected plans' share of active members.")
c1, c2 = st.columns([1.65, 1])
with c1:
    fig = go.Figure()
    fig.add_bar(x=mo["month"], y=mo["revenue"], name="Revenue", marker_color=PURPLE)
    fig.add_bar(x=mo["month"], y=mo["expenses"], name="Expenses", marker_color="rgba(244,114,182,0.55)")
    fig.add_scatter(x=mo["month"], y=mo["profit"], name="Profit", mode="lines+markers",
                    line=dict(color=TURQUOISE, width=3), marker=dict(size=6))
    fig.update_layout(barmode="group", hovermode="x unified", title="Revenue vs expenses")
    fig.update_yaxes(tickprefix="€", tickformat=",.0f")
    charts.show(fig, 360)
with c2:
    mix = F["members"]
    mix = mix[mix["status"] == "Active"]["membership_type"].value_counts()
    charts.show(charts.donut(mix.index, mix.values, "Active members by plan",
                             center=f"<b>{mix.sum():,}</b><br><span style='font-size:11px'>active</span>"), 360)

layout.section("Membership dynamics", "Net growth = new registrations − cancellations")
c1, c2 = st.columns([1.65, 1])
with c1:
    fig = go.Figure()
    fig.add_bar(x=mo["month"], y=mo["new_members"], name="New", marker_color=GREEN)
    fig.add_bar(x=mo["month"], y=-mo["churned"], name="Cancelled", marker_color=RED)
    fig.add_scatter(x=mo["month"], y=mo["active_members"], name="Active members", yaxis="y2",
                    line=dict(color=TURQUOISE, width=3), mode="lines")
    fig.update_layout(barmode="relative", hovermode="x unified", title="Member flow & active base",
                      yaxis2=dict(overlaying="y", side="right", showgrid=False, title="Active"))
    charts.show(fig, 340)
with c2:
    trend = occupancy.daily_trend(F["attendance"])
    fig = go.Figure()
    fig.add_scatter(x=trend["date"], y=trend["visits"], name="Daily visits", mode="lines",
                    line=dict(color="rgba(139,92,246,0.35)", width=1))
    fig.add_scatter(x=trend["date"], y=trend["rolling_28"], name="28-day average", mode="lines",
                    line=dict(color=TURQUOISE, width=2.6))
    fig.update_layout(title="Attendance trend", hovermode="x unified")
    charts.show(fig, 340)

layout.section("Top priorities", "Automatically generated by the Smart Insights engine")
ins = [i for i in state.get_insights() if i.severity in ("critical", "warning")][:3]
cols = st.columns(3)
for c, i in zip(cols, ins):
    with c:
        layout.insight_card(i)
st.page_link("views/7_Smart_Insights.py", label="Open all recommendations", icon=":material/arrow_forward:")
